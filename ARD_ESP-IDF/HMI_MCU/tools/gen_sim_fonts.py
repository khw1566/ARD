"""Export the firmware fonts for the PC HMI simulator.

Reads main/font8x8.h and main/korean_font.h and writes
ARD_MAIN/frontend/static/js/hmi-sim-fonts.js so the simulator draws with the
exact glyphs the board uses. Re-run after changing either header:

    python tools/gen_sim_fonts.py
"""
import base64
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT.parents[1] / "ARD_MAIN" / "frontend" / "static" / "js" / "hmi-sim-fonts.js"


def hex_bytes(text):
    return [int(v, 16) for v in re.findall(r"0x([0-9A-Fa-f]{2})\b", text)]


def main():
    f8 = (ROOT / "main" / "font8x8.h").read_text(encoding="utf-8")
    body = f8[f8.index("font8x8_basic"):]
    ascii_bytes = hex_bytes(body[: body.index("};")])
    assert len(ascii_bytes) == 128 * 8, len(ascii_bytes)

    kf = (ROOT / "main" / "korean_font.h").read_text(encoding="utf-8")
    bitmaps = kf[kf.index("hangul_bitmaps[]"):]
    bitmap_bytes = hex_bytes(bitmaps[: bitmaps.index("};")])
    index_part = kf[kf.index("hangul_index[]"):]
    index = re.findall(r"\{\s*0x([0-9A-Fa-f]+),\s*(\d+)\s*\}", index_part[: index_part.index("};")])
    codes = [int(c, 16) for c, _ in index]
    offsets = [int(o) for _, o in index]
    assert offsets == [i * 32 for i in range(len(offsets))], "index must be dense"
    assert len(bitmap_bytes) == len(codes) * 32

    OUT.write_text(
        "// Generated by ARD_ESP-IDF/HMI_MCU/tools/gen_sim_fonts.py - do not edit.\n"
        "window.HMI_SIM_FONTS = {\n"
        f"  ascii8: '{base64.b64encode(bytes(ascii_bytes)).decode()}',\n"
        f"  hangulCodes: [{','.join(str(c) for c in codes)}],\n"
        f"  hangul16: '{base64.b64encode(bytes(bitmap_bytes)).decode()}'\n"
        "};\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"wrote {OUT} ({len(codes)} Hangul glyphs)")


if __name__ == "__main__":
    main()
