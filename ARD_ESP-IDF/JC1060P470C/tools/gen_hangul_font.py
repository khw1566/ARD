"""Generate the Hangul fallback fonts (16/20/28 px, 4 bpp) from Nanum Gothic (SIL OFL 1.1).

Only characters used by the UI are included: every non-ASCII character in
main/ui_text.cpp (Korean translations) and the other UI sources, except the
degree sign and bullet that Montserrat already has. Run after changing Korean text:

    python tools/gen_hangul_font.py

Rendering follows Mini WebServer's tools/generate_ui_fonts.py (4x supersampled,
Lanczos downscale, LVGL lv_font_fmt_txt with a sparse cmap).
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
TTF = ROOT / 'third_party/nanum-gothic/NanumGothic-Regular.ttf'
SOURCES = ['ui_text.cpp', 'ui.cpp', 'ui_main.cpp', 'ui_settings.cpp', 'ui_screensaver.cpp']
MONTSERRAT_HAS = {0xB0, 0x2022}
SIZES = (16, 20, 28)
SCALE = 4


def characters():
    chars = set()
    for name in SOURCES:
        text = (ROOT / 'main' / name).read_text(encoding='utf-8')
        chars.update(c for c in text if ord(c) > 0x7F and ord(c) not in MONTSERRAT_HAS)
    return sorted(chars)


def render(chars, size):
    font = ImageFont.truetype(str(TTF), size * SCALE)
    ascent, descent = font.getmetrics()
    pad = size * SCALE
    glyphs = []
    for ch in chars:
        canvas = Image.new('L', (pad * 4, pad * 4))
        baseline = pad * 2
        ImageDraw.Draw(canvas).text((pad, baseline), ch, font=font, fill=255, anchor='ls')
        small = canvas.resize((canvas.width // SCALE, canvas.height // SCALE), Image.LANCZOS)
        advance = font.getlength(ch) / SCALE
        box = small.getbbox()
        if not box:
            glyphs.append((ch, advance, 0, 0, 0, 0, b''))
            continue
        left, top, right, bottom = box
        pixels = [p >> 4 for p in small.crop(box).tobytes()]
        if len(pixels) % 2:
            pixels.append(0)
        data = bytes((pixels[i] << 4) | pixels[i + 1] for i in range(0, len(pixels), 2))
        glyphs.append((ch, advance, right - left, bottom - top, left - pad // SCALE,
                       baseline // SCALE - bottom, data))
    return glyphs, round(ascent / SCALE), round(descent / SCALE)


def emit(size, glyphs, ascent, descent):
    name = f'ard_hangul_{size}'
    out = [f'/* {size} px Hangul fallback for the JC1060 UI. Generated by tools/gen_hangul_font.py',
           ' * from Nanum Gothic (SIL OFL 1.1, third_party/nanum-gothic/OFL.txt). Do not edit. */']
    blob = bytearray()
    descs = ['    {0},']
    for ch, advance, w, h, ox, oy, data in glyphs:
        descs.append(f'    {{.bitmap_index={len(blob)}, .adv_w={round(advance * 16)}, .box_w={w}, .box_h={h}, '
                     f'.ofs_x={ox}, .ofs_y={oy}}}, /* U+{ord(ch):04X} */')
        blob.extend(data)
    out.append(f'static const uint8_t bitmap_{size}[] = {{')
    out += ['    ' + ','.join(f'0x{c:02x}' for c in blob[i:i + 24]) + ',' for i in range(0, len(blob), 24)]
    out += ['};', f'static const lv_font_fmt_txt_glyph_dsc_t glyphs_{size}[] = {{', *descs, '};']
    codes = [ord(g[0]) for g in glyphs]
    first = codes[0]
    out.append(f'static const uint16_t unicode_list_{size}[] = {{' +
               ','.join(f'0x{c - first:x}' for c in codes) + '};')
    out += [f'static const lv_font_fmt_txt_cmap_t maps_{size}[] = {{',
            f'    {{.range_start=0x{first:x}, .range_length={codes[-1] - first + 1}, .glyph_id_start=1, '
            f'.unicode_list=unicode_list_{size}, .list_length={len(codes)}, .type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}}',
            '};', f'static const lv_font_fmt_txt_dsc_t description_{size} = {{',
            f'    .glyph_bitmap=bitmap_{size}, .glyph_dsc=glyphs_{size}, .cmaps=maps_{size}, .cmap_num=1, .bpp=4',
            '};', f'const lv_font_t {name} = {{',
            '    .get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt, .get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,',
            f'    .line_height={ascent + descent}, .base_line={descent}, .dsc=&description_{size}, .fallback=NULL',
            '};', '']
    return out, len(blob)


def main():
    chars = characters()
    lines = ['#include "lvgl.h"', '']
    total = 0
    for size in SIZES:
        glyphs, ascent, descent = render(chars, size)
        out, size_bytes = emit(size, glyphs, ascent, descent)
        lines += out
        total += size_bytes
    (ROOT / 'main/ard_font_hangul.c').write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    print(f'{len(chars)} glyphs x {len(SIZES)} sizes, {total:,} bitmap bytes -> main/ard_font_hangul.c')


if __name__ == '__main__':
    main()
